#!/usr/bin/env python3
"""Write the module sources and the generated macro test from the FriBidi headers.

- src/fribidi.cppm exports every type, enumerator, FRIBIDI_ENTRY function
  and variable of the public headers by `export using` (the upstream
  globals, unchanged), and re-exports the macros module.
- src/macros.cppm maps every macro a C++ entity can be, in
  mcpplibs::mwrap::fribidi::macros under its own name:
    * object-like macros (FRIBIDI_TYPE_*, FRIBIDI_PAR_*, FRIBIDI_MASK_*,
      FRIBIDI_FLAG(S)_*, FRIBIDI_CHAR_*, versions …) as `inline constexpr`
      with the type of the macro's own expansion (a string literal's macro is
      a reference to a constexpr char array);
    * function-like macros (FRIBIDI_IS_*, FRIBIDI_LEVEL_IS_RTL,
      FRIBIDI_TEST_BITS, FRIBIDI_SET_BITS …) as constexpr function templates
      whose body *is* the macro, expanded on the parameters: the result has
      the macro's type and value category for every argument type; a macro
      that assigns to an argument takes it by reference.
- tests/macros_mix_test.cpp checks each mapping against the raw header in a
  translation unit that includes it beside the import.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, surface  # noqa: E402

# Macros that stay macros, in <mwrap/fribidi/macros.hpp> (which is <fribidi.h>).
SIDE_HEADER = {
    'FRIBIDI_ENTRY': 'an attribute of declarations (visibility, dllimport/dllexport)',
    'FRIBIDI_EXTERN': 'a storage-class specifier of declarations',
    'FRIBIDI_GNUC_CONST': 'an attribute of declarations',
    'FRIBIDI_GNUC_DEPRECATED': 'an attribute of declarations',
    'FRIBIDI_GNUC_HIDDEN': 'an attribute of declarations',
    'FRIBIDI_GNUC_MALLOC': 'an attribute of declarations',
    'FRIBIDI_GNUC_WARN_UNUSED': 'an attribute of declarations',
    'FRIBIDI_BEGIN_DECLS': 'opens an extern "C" block',
    'FRIBIDI_END_DECLS': 'closes an extern "C" block',
    'FRIBIDI_BEGIN_IGNORE_DEPRECATIONS': 'a diagnostic pragma',
    'FRIBIDI_END_IGNORE_DEPRECATIONS': 'a diagnostic pragma',
    '_FRIBIDI_ADD_TYPE': 'an X-macro of the *-list.h tables: the includer defines it',
    '_FRIBIDI_ADD_ALIAS': 'an X-macro of the *-list.h tables: the includer defines it',
    '_FRIBIDI_ADD_CHAR_SET': 'an X-macro of the *-list.h tables: the includer defines it',
    '_FRIBIDI_ADD_CHAR_SET_OTHERS': 'an X-macro of the *-list.h tables: the includer defines it',
    '_FRIBIDI_ADD_CHAR_SET_ONE2ONE': 'an X-macro of the *-list.h tables: the includer defines it',
    '_FRIBIDI_PAR_TYPES': 'an X-macro selector of fribidi-bidi-types-list.h',
}

# A macro's parameters it assigns to: the function takes them by reference.
LVALUE = {
    'FRIBIDI_SET_BITS': {'x'},
    'FRIBIDI_UNSET_BITS': {'x'},
    'FRIBIDI_ADJUST_BITS': {'x'},
    'FRIBIDI_ADJUST_AND_TEST_BITS': {'x'},
}

# Bodies that are what upstream wrote, not what it meant: comparisons bind
# tighter than `&` (FRIBIDI_IS_LTR_LETTER is always 0, FRIBIDI_IS_RTL_LETTER
# is `p & 1`). The functions keep the macros' results; the warning is upstream's.
PARENTHESES = {'FRIBIDI_IS_LTR_LETTER', 'FRIBIDI_IS_RTL_LETTER'}


def excluded(name: str) -> str | None:
    if re.fullmatch(r'_FRIBIDI(?:_\w+)?_H|FRIBIDI_CONFIG_H', name):
        return 'include guard'
    return None


def classify(sf):
    strings, constants, functions = [], [], []
    for macro in sf.macros.values():
        if macro.name in SIDE_HEADER or excluded(macro.name):
            continue
        if macro.params is not None:
            functions.append(macro)
        elif macro.body.startswith('"'):
            strings.append(macro.name)
        else:
            constants.append(macro.name)
    return strings, constants, functions


def assigned(macro) -> set[str]:
    """The parameters a macro's body assigns to (directly or through FRIBIDI_ADJUST_BITS)."""
    out = set()
    for p in macro.params:
        if re.search(r'\(\s*' + p + r'\s*\)\s*(?:[|&^+\-*/%]?=)(?!=)', macro.body):
            out.add(p)
        if re.search(r'\bFRIBIDI_ADJUST_BITS\s*\(\s*\(\s*' + p + r'\s*\)', macro.body):
            out.add(p)
    return out


GUARD = '''#if defined(_WIN32) && !defined(FRIBIDI_LIB_STATIC)
// compat.fribidi is a static library: entry points without dllimport.
#define FRIBIDI_LIB_STATIC 1
#endif
#include <fribidi.h>'''

ROOT_HEADER = '''// Generated by tools/gen_exports.py from the GNU FriBidi 1.0.16 headers — do
// not edit by hand.
//
// mcpplibs.mwrap.fribidi — GNU FriBidi, the Unicode Bidirectional Algorithm
// (UAX #9), as a C++ module. Every exported name is the upstream global of
// <fribidi.h>, unchanged: the types, the enumerators of FriBidiCharSet and
// of the joining types, every FRIBIDI_ENTRY function (the deprecated ones
// too) and the two version strings. The root also re-exports the macro
// mappings. The library is compat.fribidi, built from the same release.
module;
''' + GUARD + '''

export module mcpplibs.mwrap.fribidi;

export import mcpplibs.mwrap.fribidi.macros;
'''

MACROS_HEADER = '''// Generated by tools/gen_exports.py from the GNU FriBidi 1.0.16 headers — do
// not edit by hand.
//
// mcpplibs.mwrap.fribidi.macros — the macros of <fribidi.h> (a named module
// cannot export a macro), under their original names in
// mcpplibs::mwrap::fribidi::macros:
//
//   - object-like macros (FRIBIDI_TYPE_*, FRIBIDI_PAR_*, FRIBIDI_MASK_*,
//     FRIBIDI_FLAG_*, FRIBIDI_FLAGS_*, FRIBIDI_CHAR_*, FRIBIDI_JOINING_TYPE_*_VAL,
//     FRIBIDI_BIDI_*, the versions, the deprecated UNI_* …) as `inline
//     constexpr`, each of the type its macro expands to in C++ (FRIBIDI_TYPE_LTR
//     is a `long`, as 0x00000110L is; FRIBIDI_PAR_RTL too), a string macro as a
//     reference to a constexpr char array;
//   - function-like macros (FRIBIDI_IS_*, FRIBIDI_LEVEL_IS_RTL,
//     FRIBIDI_DIR_TO_LEVEL, FRIBIDI_TEST_BITS, FRIBIDI_SET_BITS,
//     FRIBIDI_ARAB_SHAPES, FRIBIDI_JOINS_* …) as constexpr function templates.
//     Each body is the macro itself, expanded on the parameters while the
//     header's macros are defined (the declarator is parenthesised so the
//     name is not expanded): the result has the macro's value, type and value
//     category for every argument type. Each argument is evaluated once,
//     before the call; a macro that assigns to an argument (FRIBIDI_SET_BITS,
//     FRIBIDI_UNSET_BITS, FRIBIDI_ADJUST_BITS, FRIBIDI_ADJUST_AND_TEST_BITS)
//     takes it by reference and returns what the macro does.
//
// Attributes, extern "C" brackets, diagnostic pragmas and the X-macros of the
// *-list.h tables stay macros, in <mwrap/fribidi/macros.hpp>, included before
// the import. tools/check_exports.py accounts for every macro.
module;
''' + GUARD + '''
'''


def render_root(sf) -> str:
    out = [ROOT_HEADER]
    out.append(f'// types ({len(sf.types)})')
    out += [f'export using ::{n};' for n in sf.types]
    out.append(f'\n// enumerators of FriBidiCharSet and the joining types ({len(sf.enumerators)})')
    out += [f'export using ::{n};' for n in sf.enumerators]
    exported = [n for n in sf.functions if n not in sf.cxx_linkage]
    out.append(f'\n// functions ({len(exported)})')
    out += [f'export using ::{n};' for n in exported]
    out.append(f'\n// variables ({len(sf.variables)})')
    out += [f'export using ::{n};' for n in sf.variables]
    out.append(f'\n// declared by fribidi-common.h outside its extern "C" block ({len(sf.cxx_linkage)}): adapted')
    out.append('// under their names and signatures, each calling the library\'s C function (src/common.cpp)')
    out.append('export namespace mcpplibs::mwrap::fribidi {')
    for n in sf.cxx_linkage:
        returns, params = sf.signatures[n]
        out.append(f'extern "C++" {returns} {n}({params});')
    out.append('}  // namespace mcpplibs::mwrap::fribidi')
    return '\n'.join(out) + '\n'


def render_common(sf) -> str:
    out = ['// Generated by tools/gen_exports.py from the GNU FriBidi 1.0.16 headers — do',
           '// not edit by hand.',
           '//',
           '// fribidi-common.h declares ' + ' and '.join(sf.cxx_linkage) + ' outside',
           '// the extern "C" block every other header has, so a C++ translation unit',
           '// that includes it declares them in C++ linkage: a call cannot link, as',
           '// the library defines them in C. Each is adapted under its name and',
           '// signature in mcpplibs::mwrap::fribidi, calling the C function, declared',
           '// here as the library defines it. No FriBidi header is included.',
           'extern "C" {']
    for n in sf.cxx_linkage:
        returns, params = sf.signatures[n]
        out.append(f'{returns} {n}({params});')
    out += ['}', '', 'namespace mcpplibs::mwrap::fribidi {', '']
    for n in sf.cxx_linkage:
        returns, params = sf.signatures[n]
        args = [] if params in ('', 'void') else [re.findall(r'(\w+)\s*$', p.strip())[0] for p in params.split(',')]
        out.append(f'{returns} {n}({params}) {{ return ::{n}({", ".join(args)}); }}')
    out += ['', '}  // namespace mcpplibs::mwrap::fribidi', '']
    return '\n'.join(out)


def function(macro) -> list[str]:
    refs = LVALUE.get(macro.name, set())
    if refs != assigned(macro):
        sys.exit(f'{macro.name} assigns to {sorted(assigned(macro))}; LVALUE lists {sorted(refs)}')
    tparams = ', '.join(f'class T{i}' for i in range(len(macro.params)))
    params = ', '.join(f'T{i}{"&" if p in refs else ""} {p}' for i, p in enumerate(macro.params))
    returns = 'decltype(auto)' if refs and macro.name != 'FRIBIDI_ADJUST_AND_TEST_BITS' else 'auto'
    call = f'{macro.name}({", ".join(macro.params)})'
    if returns == 'decltype(auto)':
        call = f'({call})'
    return [f'template <{tparams}>', f'constexpr {returns} ({macro.name})({params}) noexcept {{ return {call}; }}']


def render_macros(sf) -> str:
    strings, constants, functions = classify(sf)
    out = [MACROS_HEADER]
    out.append('export module mcpplibs.mwrap.fribidi.macros;\n')
    out.append('// The header\'s values, taken while its macros are defined (module linkage).')
    out.append('namespace mwrap_fribidi_capture {')
    out += [f'inline constexpr auto value_{n} = {n};' for n in constants]
    out += [f'inline constexpr char value_{n}[] = {n};' for n in strings]
    out.append('}  // namespace mwrap_fribidi_capture\n')
    out.append('// ── computation macros, defined while the header\'s macros are ──────────────')
    out.append('export namespace mcpplibs::mwrap::fribidi::macros {\n')
    for macro in functions:
        if macro.name in PARENTHESES:
            out += ['#pragma GCC diagnostic push', '#pragma GCC diagnostic ignored "-Wparentheses"']
        out.append(f'// #define {macro.name}({", ".join(macro.params)}) {macro.body}')
        out += function(macro)
        if macro.name in PARENTHESES:
            out.append('#pragma GCC diagnostic pop')
    out.append('\n}  // namespace mcpplibs::mwrap::fribidi::macros\n')
    out.append('// Every mapped object-like name, so the definitions below are not rewritten.')
    out += [f'#undef {n}' for n in constants + strings]
    out.append('\nnamespace c = mwrap_fribidi_capture;\n')
    out.append('export namespace mcpplibs::mwrap::fribidi::macros {\n')
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    out += [f'inline constexpr auto {n} = c::value_{n};' for n in constants]
    out.append('\n// ── strings ─────────────────────────────────────────────────────────────────')
    out += [f'inline constexpr auto& {n} = c::value_{n};' for n in strings]
    out.append('\n}  // namespace mcpplibs::mwrap::fribidi::macros')
    return '\n'.join(out) + '\n'


TEST_HEADER = '''// Generated by tools/gen_exports.py from the GNU FriBidi 1.0.16 headers — do
// not edit by hand.
//
// Every macro mapping against the raw header, in one translation unit that
// includes <mwrap/fribidi/macros.hpp> (that is, <fribidi.h>) beside the import:
//
//   - each constant has its macro's type and value (the macro is set aside
//     with push_macro around the comparison: while it is defined it expands
//     even inside `m::NAME`);
//   - each function gives the macro's value, type and value category for
//     every argument of the sample sets (every bidi type, mask and flag, every
//     uint8_t joining property, every FriBidiLevel, ints and longs); a
//     function-like macro is not expanded when its name is followed by `)`,
//     so `(m::NAME)(args)` calls the function beside the macro `NAME(args)`;
//     a macro that assigns to its argument leaves the same value in it.
#include <mwrap/fribidi/macros.hpp>
#include <gtest/gtest.h>

import std;
import mcpplibs.mwrap.fribidi;

namespace m = mcpplibs::mwrap::fribidi::macros;
'''

