def render_test(sf) -> str:
    strings, constants, functions = classify(sf)
    out = [TEST_HEADER]
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    for n in constants:
        out.append(f'constexpr auto raw_{n} = {n};')
    for n in strings:
        out.append(f'using raw_type_{n} = decltype({n});')
        out.append(f'constexpr std::string_view raw_{n} = {n};')
    for n in constants:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<decltype(m::{n}), decltype(raw_{n})> && m::{n} == raw_{n});',
                f'#pragma pop_macro("{n}")']
    for n in strings:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<std::remove_cvref_t<decltype(m::{n})>, std::remove_cvref_t<raw_type_{n}>>);',
                f'static_assert(std::string_view(m::{n}) == raw_{n});',
                f'#pragma pop_macro("{n}")']
    out.append(TEST_SAMPLES)
    out.append('// ── computation macros ──────────────────────────────────────────────────────')
    for macro in functions:
        refs = LVALUE.get(macro.name, set())
        params = ', '.join(f'auto {p}' for p in macro.params)
        args = ', '.join(macro.params)
        arity = {1: 'unary', 2: 'binary', 3: 'ternary'}[len(macro.params)]
        out.append(f'TEST(MacroFunctions, {macro.name}) {{')
        if macro.name in PARENTHESES:
            out += ['#pragma GCC diagnostic push', '#pragma GCC diagnostic ignored "-Wparentheses"']
        out.append(f'    {arity}([]({params}) {{')
        if refs:
            # Both forms on their own copies: the same result, the same value left behind.
            ref = sorted(refs)[0]
            raw_args = ', '.join('a' if p == ref else p for p in macro.params)
            fn_args = ', '.join('b' if p == ref else p for p in macro.params)
            out += [f'        auto a = {ref}, b = {ref};',
                    f'        static_assert(std::is_same_v<decltype({macro.name}({raw_args})), decltype((m::{macro.name})({fn_args}))>);',
                    f'        decltype(auto) raw = {macro.name}({raw_args});',
                    f'        decltype(auto) mapped = (m::{macro.name})({fn_args});',
                    '        EXPECT_EQ(raw, mapped);',
                    '        EXPECT_EQ(a, b);']
            if macro.name != 'FRIBIDI_ADJUST_AND_TEST_BITS':
                out += ['        EXPECT_EQ(&raw, &a);  // the macro\'s lvalue: the argument itself',
                        '        EXPECT_EQ(&mapped, &b);']
        else:
            out += [f'        static_assert(std::is_same_v<decltype({macro.name}({args})), decltype((m::{macro.name})({args}))>);',
                    f'        EXPECT_EQ({macro.name}({args}), (m::{macro.name})({args}));']
        out.append('    });')
        if macro.name in PARENTHESES:
            out.append('#pragma GCC diagnostic pop')
        out.append('}')
    return '\n'.join(out) + '\n'


def outputs(root: Path) -> dict[Path, str]:
    sf = surface(fetch(root))
    return {
        root / 'src/fribidi.cppm': render_root(sf),
        root / 'src/common.cpp': render_common(sf),
        root / 'src/macros.cppm': render_macros(sf),
        root / 'tests/macros_mix_test.cpp': render_test(sf),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, text in outputs(root).items():
        # Text mode: a checkout with CRLF line ends (Windows) reads the same.
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue  # unchanged: the timestamp is kept, nothing rebuilds
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
